#!/usr/bin/env python3
"""Generate BRIDGE-03 C ABI from its versioned shared protocol specification."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SPEC=json.loads((ROOT/'bridge/ui_protocol.json').read_text())
def generate():
 out=['/* Generated by tools/generate_pi_ui.py; edit bridge/ui_protocol.json. */','#ifndef GUARD_PI_UI_H','#define GUARD_PI_UI_H','#include "global.h"',f'#define PI_UI_MAGIC {SPEC["magic"]}u',f'#define PI_UI_SCHEMA {SPEC["schema_version"]}']
 for group,prefix in [('commands','PI_UI_'),('states','PI_UI_STATE_'),('results','PI_UI_RESULT_'),('bounds','PI_UI_')]:
  for k,v in SPEC[group].items():out.append(f'#define {prefix}{k.upper()} {v}')
 out.append('struct PiUiMailbox {')
 for name,n in SPEC['mailbox_fields']:out.append(f'    u{n*8} {name};' if n in (2,4) else f'    u8 {name}[{n}];')
 out.append('};');offset=0
 for name,n in SPEC['mailbox_fields']:
  out.append(f'typedef char PiUiOffset_{name}[(offsetof(struct PiUiMailbox, {name}) == {offset}) ? 1 : -1];');offset+=n
 out.append(f'typedef char PiUiSize[(sizeof(struct PiUiMailbox) == {offset}) ? 1 : -1];')
 out.append('#define PI_UI_LAYOUT_VALUES '+', '.join(f'offsetof(struct PiUiMailbox, {name})' for name,n in SPEC['mailbox_fields']))
 out.extend(['extern volatile struct PiUiMailbox gPiUi;','void PiUi_Init(void);','void PiUi_Tick(void);','bool8 PiUi_Field(void);','bool8 PiUi_IsField(void);','void PiUi_StopPrinter(void);','#endif',''])
 (ROOT/'include/pi_ui.h').write_text('\n'.join(out))
if __name__=='__main__':generate()
