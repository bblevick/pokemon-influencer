#!/usr/bin/env python3
"""Generate the C ABI from the single reviewed protocol schema."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
S=json.loads((ROOT/'bridge/protocol.json').read_text())

def layout():
    offset=0; fields={}
    for name,kind in S['fields']:
        size={'u32':4,'u16':2,'bytes32':32}[kind]
        assert offset % (4 if kind=='u32' else 2 if kind=='u16' else 1)==0
        fields[name]={'offset':offset,'size':size,'kind':kind};offset+=size
    assert offset%4==0
    return fields,offset

def generate():
    fields,size=layout()
    lines=['/* Generated by tools/generate_pi_protocol.py. Do not edit. */',
           '#ifndef GUARD_PI_PROTOCOL_H','#define GUARD_PI_PROTOCOL_H',
           '#include "global.h"','#include <stddef.h>',
           '#define PI_MAGIC %du'%S['magic'],'#define PI_VERSION %d'%S['protocol_version'],
           '#define PI_PAYLOAD_MAX %d'%S['payload_max'],'#define PI_TIMEOUT_FRAMES %d'%S['timeout_frames']]
    for group,prefix in [('states','STATE'),('types','TYPE'),('errors','ERR')]:
        lines.extend('#define PI_%s_%s %d'%(prefix,k,v) for k,v in S[group].items())
    lines+=['struct PiMailbox {']
    for name,kind in S['fields']:
        lines.append('    u8 payload[PI_PAYLOAD_MAX];' if kind=='bytes32' else '    %s %s;'%(kind,name))
    lines+=['};','typedef char PiSizeCheck[(sizeof(struct PiMailbox) == %d) ? 1 : -1];'%size]
    for name,field in fields.items():
        lines.append('typedef char PiOffset_%s[(offsetof(struct PiMailbox, %s) == %d) ? 1 : -1];'%(name,name,field['offset']))
    lines+=['extern volatile struct PiMailbox gPiMailbox;','void PiBridge_Init(void);','void PiBridge_Tick(void);','#endif','']
    (ROOT/'include/pi_protocol.h').write_text('\n'.join(lines))
    return fields,size
if __name__=='__main__':generate()
