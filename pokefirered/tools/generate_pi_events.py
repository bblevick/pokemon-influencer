#!/usr/bin/env python3
"""Generate the C ABI from the single reviewed protocol schema."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
S=json.loads((ROOT/'bridge/events_protocol.json').read_text())

def layout():
    offset=0; fields={}
    for name,kind in S['fields']:
        size={'u32':4,'u16':2,'bytes96':96}[kind]
        assert offset % (4 if kind=='u32' else 2 if kind=='u16' else 1)==0
        fields[name]={'offset':offset,'size':size,'kind':kind};offset+=size
    assert offset%4==0
    return fields,offset

def generate():
    fields,size=layout()
    lines=['/* Generated by tools/generate_pi_events.py. Do not edit. */',
           '#ifndef GUARD_PI_EVENTS_H','#define GUARD_PI_EVENTS_H',
           '#include "global.h"','#include <stddef.h>',
           '#define PI_MAGIC %du'%S['magic'],'#define PI_VERSION %d'%S['protocol_version'],
           '#define PI_PAYLOAD_MAX %d'%S['payload_max'],'#define PI_TIMEOUT_FRAMES %d'%S['timeout_frames']]
    for group,prefix in [('states','STATE'),('types','TYPE'),('errors','ERR'),('events','EVENT'),('phases','PHASE')]:
        lines.extend('#define PI_%s_%s %d'%(prefix,k,v) for k,v in S[group].items())
    lines+=['struct PiEventMailbox {']
    for name,kind in S['fields']:
        lines.append('    u8 payload[PI_PAYLOAD_MAX];' if kind=='bytes96' else '    %s %s;'%(kind,name))
    lines+=['};','typedef char PiSizeCheck[(sizeof(struct PiEventMailbox) == %d) ? 1 : -1];'%size]
    for name,field in fields.items():
        lines.append('typedef char PiOffset_%s[(offsetof(struct PiEventMailbox, %s) == %d) ? 1 : -1];'%(name,name,field['offset']))
    lines+=['void PiEvents_Enqueue(u16 type, u16 phase, const u8 *data, u16 length);','void PiEvents_BattleStart(void);','void PiEvents_Turn(void);','void PiEvents_NextTurn(void);','void PiEvents_Reveal(void);','void PiEvents_Action(u8 actor, u8 kind);','void PiEvents_End(void);','extern volatile struct PiEventMailbox gPiMailbox;','void PiBridge_Init(void);','void PiBridge_Tick(void);','#endif','']
    (ROOT/'include/pi_events.h').write_text('\n'.join(lines))
    return fields,size
if __name__=='__main__':generate()
